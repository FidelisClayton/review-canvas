import { describe, expect, it } from "vitest";
import { layerOf, noiseOf, subjectPathCandidates } from "./classify.js";

describe("layerOf", () => {
  it.each([
    ["db/migrate/2026_add_x.rb", "data"],
    ["app/models/case/timeline.rb", "data"],
    ["app/events/case/assigned.rb", "domain"],
    ["lib/workos/client.rb", "domain"],
    ["app/jobs/sync_job.rb", "jobs"],
    ["lib/tasks/workos.rake", "jobs"],
    ["app/mailers/sync_mailer.rb", "mail"],
    ["app/views/sync_mailer/digest.html.erb", "mail"],
    ["config/routes.rb", "http"],
    ["app/serializers/x_serializer.rb", "http"],
    ["typespec/apis/backoffice/cases.tsp", "http"],
    ["app/frontend/ui/Badge.tsx", "frontend"],
    ["docs/identity.md", "other"],
  ])("%s → %s", (path, layer) => expect(layerOf(path)).toBe(layer));

  it("puts a test in its subject's band", () => {
    expect(layerOf("test/models/membership_test.rb")).toBe("data");
    expect(layerOf("test/controllers/backoffice_api/v1/cases_controller_test.rb")).toBe("http");
    expect(layerOf("app/frontend/ui/Badge.test.tsx")).toBe("frontend");
  });
});

describe("subjectPathCandidates", () => {
  it("maps Minitest, RSpec and colocated JS tests to their subjects", () => {
    expect(subjectPathCandidates("test/models/case_test.rb")).toContain("app/models/case.rb");
    expect(subjectPathCandidates("spec/jobs/sync_job_spec.rb")).toContain("app/jobs/sync_job.rb");
    expect(subjectPathCandidates("test/lib/workos/client_test.rb")).toContain("lib/workos/client.rb");
    expect(subjectPathCandidates("app/frontend/ui/Badge.test.tsx")).toContain("app/frontend/ui/Badge.tsx");
  });
});

describe("noiseOf", () => {
  it.each([
    ["yarn.lock", "generated"],
    ["db/schema.rb", "generated"],
    ["app/frontend/__snapshots__/Badge.test.tsx.snap", "generated"],
    ["app/frontend/clients/backoffice-api/schemas/case.zod.ts", "api"],
    ["typespec/openapi/BackofficeApi.openapi.yaml", "api"],
    ["config/locales/es.yml", "i18n"],
    ["app/frontend/i18n/translationKeys.d.ts", "i18n"],
    ["test/models/case_test.rb", "tests"],
    ["app/frontend/test-support/msw/handlers/admin.ts", "tests"],
  ])("%s is %s", (path, kind) => expect(noiseOf(path, null)?.kind).toBe(kind));

  it("leaves the hand-written TypeSpec contract on the course", () => {
    expect(noiseOf("typespec/apis/backoffice/case-rotation.tsp", null)).toBeNull();
  });

  it("reads generated markers from the top of the file", () => {
    expect(noiseOf("app/graphql/schema.ts", "// Code generated by gqlgen. DO NOT EDIT.")?.kind).toBe("generated");
    expect(noiseOf("app/models/case.rb", "class Case < ApplicationRecord")).toBeNull();
  });
});
