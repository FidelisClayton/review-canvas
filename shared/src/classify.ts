import type { LayerId, NoiseKind } from "./types.js";

type FilterId = Exclude<NoiseKind, "generated">;

// Layer and noise rules are plain path patterns so the reviewer can read them in the UI and so
// the same file always lands in the same place. Content checks (generated-file headers) live
// in `generatedHeader`, fed by whatever the server could read of the file.

const LAYER_RULES: [RegExp, LayerId][] = [
  [/^db\/(migrate|schema\.rb|structure\.sql)|^app\/models\//, "data"],
  [/^app\/mailers\/|^app\/views\/[^/]*_mailer\/|^app\/views\/layouts\/mailer/, "mail"],
  [/^app\/(jobs|workers|sidekiq)\/|^lib\/tasks\/|^config\/(recurring|schedule|sidekiq)[^/]*$/, "jobs"],
  [/^app\/(services|events|lib|interactors|commands|queries|forms|validators|domain|operations)\/|^lib\//, "domain"],
  [/^config\/routes|^app\/(controllers|policies|serializers|graphql|channels|views|helpers)\/|^typespec\//, "http"],
  [/^app\/(frontend|javascript|assets)\/|^(src|web|client|frontend)\/|\.(tsx|jsx|css|scss|vue|svelte)$/, "frontend"],
];

/** Where a test's subject lives, so tests sit in the subject's band. */
export function subjectPathCandidates(path: string): string[] {
  const out: string[] = [];
  const js = /^(.*)\.(test|spec)\.(tsx?|jsx?)$/.exec(path);
  if (js) {
    for (const ext of ["tsx", "ts", "jsx", "js"]) out.push(`${js[1]}.${ext}`);
    return out;
  }
  const rb = /^(test|spec)\/(.*)_(test|spec)\.rb$/.exec(path);
  if (rb) {
    const rest = rb[2]!;
    if (rest.startsWith("lib/")) out.push(`${rest}.rb`);
    else if (rest.startsWith("tasks/")) out.push(`lib/${rest}.rake`);
    else out.push(`app/${rest}.rb`, `lib/${rest}.rb`);
  }
  return out;
}

export function layerOf(path: string): LayerId {
  if (isTestPath(path)) {
    for (const candidate of subjectPathCandidates(path)) {
      const layer = layerOfSource(candidate);
      if (layer !== "other") return layer;
    }
  }
  return layerOfSource(path);
}

function layerOfSource(path: string): LayerId {
  for (const [re, layer] of LAYER_RULES) if (re.test(path)) return layer;
  return "other";
}

const TEST_PATH = /(^|\/)(test|tests|spec|__tests__|e2e|test-support)\/|_(test|spec)\.rb$|\.(test|spec)\.[jt]sx?$/;
export const isTestPath = (path: string) => TEST_PATH.test(path);

export interface FilterRule {
  id: FilterId;
  label: string;
  /** Short word for counts: "2 test", "4 generated API". */
  short: string;
  plural: string;
  patterns: string;
  note?: string;
  defaultOn: boolean;
  test: (path: string) => boolean;
}

export const FILTER_RULES: FilterRule[] = [
  {
    id: "tests",
    label: "Tests",
    short: "test",
    plural: "tests",
    patterns: "test/** · *_test.rb · *.test.tsx · spec/** · test-support/**",
    defaultOn: false,
    test: isTestPath,
  },
  {
    id: "i18n",
    label: "Translations (i18n)",
    short: "i18n",
    plural: "translation files",
    patterns: "config/locales/** · **/locales/** · **/i18n/** · translationKeys.d.ts",
    defaultOn: false,
    test: (p) => /(^|\/)(locales?|i18n|translations)\/|translationKeys\.d\.ts$|\.(po|pot|xliff)$/.test(p),
  },
  {
    id: "api",
    label: "Generated API clients",
    short: "generated API",
    plural: "generated API files",
    patterns: "app/frontend/clients/** · *.zod.ts · typespec/openapi/** · *.openapi.yaml",
    note: "Made by orval and tsp compile. The .tsp change stays on the course.",
    defaultOn: true,
    test: (p) =>
      /(^|\/)app\/frontend\/clients\/|\.zod\.ts$|^typespec\/openapi\/|\.openapi\.(ya?ml|json)$|(^|\/)openapi\.(ya?ml|json)$|(^|\/)swagger\.(ya?ml|json)$/.test(p),
  },
];

const ALWAYS_GENERATED: [RegExp, string][] = [
  [/(^|\/)(yarn\.lock|package-lock\.json|pnpm-lock\.yaml|bun\.lockb?|Gemfile\.lock|Cargo\.lock|poetry\.lock|composer\.lock|go\.sum)$/, "Lockfile."],
  [/^db\/(schema\.rb|structure\.sql)$/, "Schema dump, generated from the migrations."],
  [/\.snap$|(^|\/)__snapshots__\//, "Test snapshot output."],
  [/(^|\/)(dist|build|vendor\/assets)\/|\.min\.(js|css)$|\.map$/, "Build output."],
];

/** Generated-file markers tools write at the top of a file. */
const GENERATED_HEADER = /(do not edit|@generated|code generated by|auto-?generated|automatically generated|generated by orval)/i;

export function generatedHeader(head: string): boolean {
  return GENERATED_HEADER.test(head.slice(0, 1200));
}

/**
 * Noise for one file. Path rules decide first so a generated API client counts as "api" (a filter
 * the reviewer can turn off) rather than "generated" (always hidden).
 */
export function noiseOf(path: string, head: string | null): { kind: NoiseKind; reason: string } | null {
  for (const [re, reason] of ALWAYS_GENERATED) if (re.test(path)) return { kind: "generated", reason };
  for (const rule of FILTER_RULES) {
    if (rule.test(path)) {
      const reason =
        rule.id === "api"
          ? "Generated API client."
          : rule.id === "i18n"
            ? "Translation file."
            : "Test.";
      return { kind: rule.id, reason };
    }
  }
  if (head && generatedHeader(head)) return { kind: "generated", reason: "Marked as generated at the top of the file." };
  return null;
}

export const filterRule = (id: FilterId) => FILTER_RULES.find((r) => r.id === id)!;
